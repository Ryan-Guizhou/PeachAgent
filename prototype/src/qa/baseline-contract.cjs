'use strict';
const assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path'), vm=require('node:vm');
const {setup}=require('./expanded-harness.cjs');
async function main(){
  const {S,R,context,storage}=setup();
  const base=path.resolve(__dirname,'..');
  let current={owner:'demo',id:'default',storageKey:'otryx-studio-demo'};
  let stops=0;
  context.window.StudioSpaces={active:()=>current};
  context.window.StudioAuth={stopWorkspace:reason=>{assert.equal(reason,'project-switch');stops++;return true;}};
  S.modal=()=>{};S.drawer=S.modal;S.closeModal=()=>{};
  for(const file of ['projects.js','credentials.js','inbox.js'])vm.runInContext(fs.readFileSync(path.join(base,file),'utf8'),context,{filename:file});
  const P=context.window.StudioProjects;P.attach(S);
  assert.equal(P.active().storageKey,current.storageKey);
  const project=P.create('版本来源');
  const example=S.ContentStore.saveContent({type:'prompt',name:'来源模板',content:'原始内容 {{主题}}'});
  const model=S.Models.list({type:'llm',enabled:true})[0];
  const provider=S.Models.providers().find(x=>x.id===model.providerId);
  const kb=S.ContentStore.saveKnowledge({name:'来源知识库',settings:{chunkSize:500,overlap:50}});
  S.ContentStore.addDocument(kb.id,{name:'示例正文',content:'跨项目知识测试'});
  storage.set(P.storageKey(current,project.id),JSON.stringify({contentStore:{contents:[example],knowledge:[kb]},modelRegistry:{models:[model],providers:[provider]}}));
  const entries=P.importable(project.id);
  const copy=P.importContent(project.id,example.id,example.version,'目标模板');
  assert.equal(copy.origin.projectId,project.id);assert.equal(copy.content,example.content);
  assert.throws(()=>P.importContent(project.id,example.id,'missing','错误版本'),/版本/);
  const k=entries.find(x=>x.type==='knowledge'),kc=P.importResource(project.id,k.id,k.version,k.type,'目标知识库');
  assert.equal(S.ContentStore.getKnowledge(kc.id).documents[0].content,'跨项目知识测试');
  const m=entries.find(x=>x.type==='model'),mc=P.importResource(project.id,m.id,m.version,m.type,'目标模型');
  const copied=S.Models.resolve(mc.id,{enabled:false});
  assert.equal(copied.enabled,false);assert.equal(S.Models.providers().find(x=>x.id===copied.providerId).credentialRef,'');
  S.dirty=true;assert.throws(()=>P.switchTo(project.id),/保存/);S.dirty=false;
  assert(P.switchTo(project.id));assert.equal(stops,1);assert.notEqual(P.active().storageKey,current.storageKey);
  assert(P.switchTo('default'));assert.equal(stops,2);P.archive(project.id);assert(!P.canDelete(project.id));
  const empty=P.create('空项目');P.archive(empty.id);assert(P.canDelete(empty.id));P.remove(empty.id);
  current={owner:'another',id:'default',storageKey:'other'};assert.equal(P.list().length,1);current={owner:'demo',id:'default',storageKey:'otryx-studio-demo'};
  console.log('PASS: project storage isolation, lifecycle, pinned content / knowledge / disabled model copies');
  const C=S.Credentials;
  assert.throws(()=>C.register('model','raw-key','Invalid'),e=>e.code==='CREDENTIAL_REFERENCE_INVALID');
  C.register('model','env:QA_KEY','QA model');C.bind('model','env:QA_KEY',provider.id);
  const snap=S.Models.snapshot(model.id);assert.equal(C.change('model','env:QA_KEY','rotate').revision,2);
  C.change('model','env:QA_KEY','revoke');assert.throws(()=>S.Models.resolve(model.id),e=>e.code==='CREDENTIAL_REVOKED');
  assert.throws(()=>S.Models.assertAvailable(snap),e=>e.code==='CREDENTIAL_REVOKED');
  C.register('model','env:QA_KEY_NEW','QA new');C.bind('model','env:QA_KEY_NEW',provider.id);
  assert(S.Models.resolve(model.id));
  const conn=R.getConnection('mcp-search'), toolRef='credentialRef.qa_search';
  C.register('tool',toolRef,'Search');C.bind('tool',toolRef,conn.id);assert(R.testConnection(conn.id).ok);
  C.change('tool',toolRef,'revoke');
  const denied=R.testTool('web.search',{query:'revoked',limit:1},{speed:0});await R.waitForRun(denied);assert.equal(denied.status,'failed');assert.equal(denied.toolCalls[0].error.code,'CREDENTIAL_REVOKED');
  assert(!R.testConnection(conn.id).ok);
  console.log('PASS: credential metadata, rotation, rebinding and execution revocation');
  const agent=S.state.agents.find(x=>x.id==='research');
  const run=S.AgentStudio.start({agentId:agent.id,goal:'研究结论并写入 /知识库/测试',mode:'chat'});await R.waitForRun(run);assert.equal(run.status,'failed');assert.equal(run.errorCode,'MODE_REQUIRES_AGENT');assert.equal(run.toolCalls.length,0);
  const plan=S.AgentStudio.start({agentId:agent.id,goal:'生成研究计划',mode:'plan'});await R.waitForRun(plan);assert.equal(plan.status,'done',plan.error);assert.equal(plan.toolCalls.length,0);
  console.log('PASS: read-only Chat and non-executing Plan policy');
  const manifestAsset=S.Ecosystem.shareable().find(x=>x.type==='plugin');
  assert(manifestAsset);const manifest=JSON.parse(manifestAsset.content);assert(manifest.actions.length);assert(!('credentialRef' in manifest));
  const fields={'#eco-public-description':{value:'公开插件用途与安装方式完整说明'},'#eco-publish-consent':{checked:true,setAttribute(){},focus(){}},'#eco-publish-consent-error':{textContent:''}};
  context.document.querySelector=selector=>selector==='#eco-publish-form'?{querySelector:k=>fields[k]}:null;
  S.validate=()=>true;
  S.actions['eco-publish-confirm']({dataset:{id:manifestAsset.id,version:manifestAsset.version},disabled:false});
  const review=S.state.reviews.find(x=>x.assetId===manifestAsset.id&&x.type==='plugin');assert(review);assert.equal(review.status,'pending');
  assert(!S.Ecosystem.allResources().some(x=>x.id==='community-'+review.id));
  assert(S.Inbox.list().some(x=>x.kind==='review'&&x.id===review.id));
  S.state.role='admin';assert(S.Inbox.list().some(x=>x.id===review.id&&x.actionable));
  S.actions['eco-review-approve']({dataset:{id:review.id}});assert.equal(review.status,'approved');
  assert(S.Ecosystem.allResources().some(x=>x.id==='community-'+review.id));
  S.actions['eco-install']({dataset:{id:'community-'+review.id},disabled:false});
  S.forms['cap-import-form']({elements:{namedItem:key=>({value:key==='manifest'?review.content:'community-'+review.id})}});
  assert(R.plugins.some(x=>x.marketId==='community-'+review.id));
  const snapshots=['projects','credentials','inbox'].map(route=>({route,html:S.pages[route].render()}));
  fs.mkdirSync(path.join(__dirname,'.generated'),{recursive:true});fs.writeFileSync(path.join(__dirname,'.generated','baseline-rendered.json'),JSON.stringify(snapshots));
  console.log('PASS: public plugin review / installation, inbox and new page markup');
}
main().catch(error=>{console.error(error);process.exitCode=1;});
